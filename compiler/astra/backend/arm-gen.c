static uint32_t vfpr(int r)
{
  if(r<TREG_F0 || r>TREG_F7)
    astra_error("compiler error! register %i is no vfp register",r);
  return r - TREG_F0;
}
#else
static uint32_t fpr(int r)
{
  if(r<TREG_F0 || r>TREG_F3)
    astra_error("compiler error! register %i is no fpa register",r);
  return r - TREG_F0;
}
