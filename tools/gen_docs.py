#!/usr/bin/env python3
"""Auto-generate A language docs from stdlib source (pydoc analog).

Like Python's ``inspect.getdoc`` + ``pydoc`` + Sphinx `module_docs.py`
(which is autogenerated), this walks ``stdlib/std/**/*.a``, finds `##`
doc comments immediately before ``fn``/``class``/``enum``/``trait``
declarations, and emits:

* ``compiler/stages/name-resolution/builtin_docs.hpp`` (replaces the
  hardcoded table — the .a files become the single source of truth)
* ``docs/standard-library/auto/*.md`` (rendered docs, `a doc` style)
* ``docs/standard-library/auto.json`` (machine-readable, for LSP/hover)

Usage: ``python3 tools/gen_docs.py [--check]``

Run ``--write`` (default) to regenerate; ``--check`` exits non-zero when
generated files are stale (CI-guard, like Sphinx's apidoc check).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STDLIB = ROOT / "stdlib" / "std"
DOCS_OUT = ROOT / "docs" / "standard-library" / "auto"
HEADER_OUT = ROOT / "compiler" / "stages" / "name-resolution" / "builtin_docs.hpp"

FN_RE = re.compile(r"^\s*fn\s+([A-Za-z_]\w*)\s*\(([^)]*)\)\s*(?:->\s*([^:\n]+))?\s*:\s*$")
STRUCT_RE = re.compile(r"^\s*(?:class|enum|trait)\s+([A-Za-z_]\w*)")
METHOD_SIG_RE = re.compile(r"^\s*fn\s+([A-Za-z_]\w*)\s*\(([^)]*)\)\s*(?:->\s*([^:\n]+))?\s*:\s*$")

def strip_doc(line: str) -> str:
    s = line.strip()
    if s.startswith("##"):
        s = s[2:]
    if s.startswith(" "):
        s = s[1:]
    return s.rstrip("\r\n")

def parse_file(path: Path):
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    items = []
    pending_doc: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("##"):
            pending_doc.append(strip_doc(line))
            continue
        m = FN_RE.match(line)
        if m and pending_doc:
            name = m.group(1)
            params = m.group(2).strip()
            ret = (m.group(3) or "").strip()
            sig = f"{name}({params})" + (f" -> {ret}" if ret else "")
            doc = "\n".join(pending_doc).strip()
            # split: short summary | rest | example (>>> lines) | see also
            example_lines = []
            body_lines = []
            in_example = False
            see_also = ""
            for dl in doc.splitlines():
                dl_s = dl.strip()
                if dl_s.startswith(">>>"):
                    in_example = True
                if in_example:
                    example_lines.append(dl)
                elif dl_s.lower().startswith("see also:"):
                    see_also = dl_s[len("see also:"):].strip()
                else:
                    body_lines.append(dl)
            body = "\n".join(body_lines).strip()
            # short summary = first non-empty line
            summary = ""
            rest = []
            for bl in body.splitlines():
                if not summary and bl.strip():
                    summary = bl.strip()
                elif summary:
                    rest.append(bl)
            items.append({
                "name": name,
                "signature": sig,
                "doc": summary,
                "rest": "\n".join(rest).strip(),
                "example": "\n".join(example_lines).strip(),
                "see_also": see_also,
                "file": str(path.relative_to(ROOT)),
                "line": len(lines),
            })
            pending_doc = []
            continue
        if stripped == "":
            continue
        # any other statement resets pending doc
        if stripped.startswith("#") and not stripped.startswith("##"):
            continue
        pending_doc = []
    return items

def collect():
    all_items = {}
    for path in sorted(STDLIB.rglob("*.a")):
        for item in parse_file(path):
            # package prefix: builtin/math/json/... from path
            rel = path.relative_to(STDLIB)
            pkg = rel.parts[0] if len(rel.parts) > 1 else "builtin"
            # native key mapping: stdlib wrappers delegate to native builtins:
            # math*sqrt -> sqrt, builtin*Int -> int, etc. Keep both names.
            key = item["name"]
            if key not in all_items:
                all_items[key] = item
    return all_items

def render_header(items: dict) -> str:
    lines = []
    lines.append("#pragma once")
    lines.append("")
    lines.append("// GENERATED from stdlib/std/**/*.a by tools/gen_docs.py (similar to")
    lines.append("// pydoc_data/module_docs.py, which is autogenerated by Sphinx from")
    lines.append("// Lib/*.py docstrings). Do not hand-edit: edit the ## doc comments in")
    lines.append("// stdlib source files and re-run ``python3 tools/gen_docs.py``.")
    lines.append("//")
    lines.append("// The .a files are the single source of truth: LSP hover, go-to-def")
    lines.append("// docs and `a doc` all read the same ## comments via inspect-like")
    lines.append("// extraction (parse_file above), exactly as Python's pydoc does.")
    lines.append("#include <string>")
    lines.append("")
    lines.append("#include \"collections/transparent_map.hpp\"")
    lines.append("")
    lines.append("namespace a {")
    lines.append("")
    lines.append("struct BuiltinDoc {")
    lines.append("  const char* name;")
    lines.append("  const char* signature;")
    lines.append("  const char* documentation;")
    lines.append("  const char* example = nullptr;")
    lines.append("  const char* seeAlso = nullptr;")
    lines.append("};")
    lines.append("")
    lines.append("inline const StringMap<BuiltinDoc>& builtinDocs() {")
    lines.append("  static const StringMap<BuiltinDoc> docs = {")
    def cstr(s: str) -> str:
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    for name in sorted(items):
        it = items[name]
        doc = it["doc"].replace('"', "'").replace("\n", " ").strip()
        full = it["doc"]
        if it["rest"]:
            full = it["doc"] + "\n\n" + it["rest"]
        lines.append(f'      {{{cstr(name)}, {{{cstr(name)}, {cstr(it["signature"])}, {cstr(full)},'
                         f' {cstr(it["example"])}, {cstr(it["see_also"])}}}}},')
    lines.append("  };")
    lines.append("  return docs;")
    lines.append("}")
    lines.append("")
    lines.append("inline const BuiltinDoc* findBuiltinDoc(const std::string& name) {")
    lines.append("  const auto found = builtinDocs().find(name);")
    lines.append("  return found == builtinDocs().end() ? nullptr : &found->second;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace a")
    lines.append("")
    return "\n".join(lines)

def render_markdown(items: dict) -> str:
    out = ["# A standard library (auto-generated docs)\n",
           "> Generated from `stdlib/std/**/*.a` by `tools/gen_docs.py` (pydoc analog).",
           "> Source of truth is the `##` doc comments in the .a files; LSP hover and `a doc`",
           "> render the same text.\n"]
    for name in sorted(items):
        it = items[name]
        out.append(f"## `{it['signature']}`\n")
        out.append(it["doc"] + "\n")
        if it["rest"]:
            out.append(it["rest"] + "\n")
        if it["example"]:
            out.append("**Example:**\n```a\n" + it["example"] + "\n```\n")
        if it["see_also"]:
            out.append(f"*See also: {it['see_also']}*\n")
        out.append(f"`{it['file']}`\n")
    return "\n".join(out)

def main() -> int:
    check = "--check" in sys.argv
    items = collect()
    print(f"gen_docs: found {len(items)} documented functions in {STDLIB.relative_to(ROOT)}", file=sys.stderr)
    header = render_header(items)
    md = render_markdown(items)
    j = json.dumps({k: {"signature": v["signature"], "doc": v["doc"], "example": v["example"], "see_also": v["see_also"], "file": v["file"]} for k, v in items.items()}, indent=2, sort_keys=True)
    stale = False
    for out_path, content in [(HEADER_OUT, header), (DOCS_OUT / "README.md", md), (ROOT / "docs" / "standard-library" / "auto.json", j)]:
        if check:
            if not out_path.exists() or out_path.read_text(encoding="utf-8") != content:
                print(f"STALE: {out_path.relative_to(ROOT)}", file=sys.stderr)
                stale = True
        else:
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(content, encoding="utf-8")
            print(f"wrote {out_path.relative_to(ROOT)}", file=sys.stderr)
    return 1 if stale else 0

if __name__ == "__main__":
    raise SystemExit(main())
